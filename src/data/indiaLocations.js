// Data validation utility functions
export const validateAddressForm = (form) => {
  const errors = {};

  // Phone: 10 digits starting with 6-9
  const phoneClean = (form.phone || '').replace(/[^0-9]/g, '');
  if (!phoneClean || phoneClean.length !== 10 || !/^[6-9]/.test(phoneClean)) {
    errors.phone = 'Enter valid 10-digit Indian Mobile Number (e.g. 7990648756)';
  }

  // Pincode: 6 digits
  const pinClean = (form.pincode || '').replace(/[^0-9]/g, '');
  if (!pinClean || pinClean.length !== 6) {
    errors.pincode = 'Enter valid 6-digit Indian PIN Code (e.g. 363641)';
  }

  // Email validation
  if (!form.email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(form.email.trim())) {
    errors.email = 'Enter valid email address (e.g. customer@gmail.com)';
  }

  // Name
  if (!form.customerName || form.customerName.trim().length < 2) {
    errors.customerName = 'Enter full customer name';
  }

  // Address
  if (!form.address || form.address.trim().length < 5) {
    errors.address = 'Enter complete street / house address';
  }

  // State, District, Village
  if (!form.state) errors.state = 'Please select state';
  if (!form.district) errors.district = 'Please select district';
  if (!form.city) errors.city = 'Please select village / taluka / city';

  return {
    isValid: Object.keys(errors).length === 0,
    errors
  };
};
